if ("IntersectionObserver" in window && !motionOff) {
  revealItems.forEach((item) => item.classList.add("reveal"));
  const observer = new IntersectionObserver(
    (entries, currentObserver) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          currentObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 },
  );
  revealItems.forEach((item) => observer.observe(item));
}

// A small, optional star field. If canvas is unavailable, the CSS background remains intact.
const canvas = document.querySelector(".sky");
const context = canvas?.getContext("2d", { alpha: true });
if (context) {
  let width = 0,
    height = 0,
    stars = [],
    frame = 0;
  const pointer = { x: -1000, y: -1000, until: 0 };
  function resize() {
    const pixelRatio = Math.min(window.devicePixelRatio || 1, 1.5);
    width = window.innerWidth;
    height = window.innerHeight;
    canvas.width = Math.round(width * pixelRatio);
    canvas.height = Math.round(height * pixelRatio);
    context.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);
    stars = Array.from(
      { length: Math.min(95, Math.floor((width * height) / 11000)) },
      () => ({
        x: Math.random() * width,
        y: Math.random() * height,
        r: Math.random() * 1.25 + 0.25,
        phase: Math.random() * Math.PI * 2,
        speed: 0.0004 + Math.random() * 0.001,
      }),
    );
  }
  function draw(time) {
    context.clearRect(0, 0, width, height);
    for (const star of stars) {
      const opacity =
        0.2 + (Math.sin(time * star.speed + star.phase) + 1) * 0.23;
      context.beginPath();
      context.arc(star.x, star.y, star.r, 0, Math.PI * 2);
      context.fillStyle = `rgba(190, 204, 255, ${opacity})`;
      context.fill();
    }
    if (time < pointer.until) {
      const progress = 1 - (pointer.until - time) / 850;
      context.beginPath();
      context.arc(pointer.x, pointer.y, progress * 75, 0, Math.PI * 2);
      context.strokeStyle = `rgba(144, 242, 209, ${(1 - progress) * 0.3})`;
      context.lineWidth = 1;
      context.stroke();
    }
    if (!motionOff) frame = requestAnimationFrame(draw);
  }
  resize();
  if (!motionOff) frame = requestAnimationFrame(draw);
  else draw(0);
  window.addEventListener("resize", resize, { passive: true });
  window.addEventListener(
    "pointerdown",
    (event) => {
      pointer.x = event.clientX;
      pointer.y = event.clientY;
      pointer.until = performance.now() + 850;
      if (motionOff) draw(0);
    },
    { passive: true },
  );
  document.addEventListener("visibilitychange", () => {
    if (document.hidden) cancelAnimationFrame(frame);
    else if (!motionOff) frame = requestAnimationFrame(draw);
  });
}
